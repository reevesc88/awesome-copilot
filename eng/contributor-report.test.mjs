import assert from "node:assert/strict";
import { test } from "node:test";
import {
  generateMarkdownReport,
  generatePRReport,
  getContributionTypes,
  getFileContributionType,
  globToRegExp,
  isAutoGeneratedFile,
  matchGlob,
  parseMissingContributorsOutput,
  parseRepoFromRemoteUrl,
} from "./contributor-report.mjs";
import {
  evaluateRefShaConsistency,
  normalizeCommitSha,
} from "./lib/external-plugin-source-ref-sha.mjs";

test("globToRegExp and matchGlob support single and double wildcards across separators", () => {
  assert.ok(globToRegExp("plugins/**/plugin.json") instanceof RegExp);
  assert.equal(matchGlob("plugins/my-pack/plugin.json", "plugins/**/plugin.json"), true);
  assert.equal(matchGlob("instructions\\rust.instructions.md", "instructions/*.instructions.md"), true);
  assert.equal(matchGlob("instructions/nested/rust.instructions.md", "instructions/*.instructions.md"), false);
});

test("isAutoGeneratedFile and getContributionTypes classify substantive files and ignore generated docs", () => {
  assert.equal(isAutoGeneratedFile("README.md"), true);
  assert.equal(isAutoGeneratedFile("docs/README.agents.md"), true);
  assert.equal(isAutoGeneratedFile("CONTRIBUTING.md"), false);

  assert.equal(getFileContributionType("agents/reviewer.agent.md"), "agents");
  assert.equal(getFileContributionType("instructions/go.instructions.md"), "instructions");
  assert.equal(getFileContributionType("plugins/demo/plugin.json"), "plugins");
  assert.equal(getFileContributionType("eng/update-readme.mjs"), "code");

  assert.equal(getContributionTypes(["README.md", "docs/README.skills.md"]), "");
  assert.equal(
    getContributionTypes([
      "README.md",
      "agents/helper.agent.md",
      "instructions/style.instructions.md",
      "eng/helper.mjs",
    ]),
    "agents,code,instructions",
  );
});

test("generateMarkdownReport handles zero missing contributors and formats sorted PR entries", () => {
  assert.equal(generateMarkdownReport([], 0), "No missing contributors detected.\n");

  const md = generateMarkdownReport(
    [
      {
        username: "octocat",
        totalPRs: 2,
        prs: [
          {
            prNumber: 10,
            prTitle: "Older PR",
            prUrl: "https://github.com/example/repo/pull/10",
            mergedAt: "2026-01-01T00:00:00Z",
            contributionTypes: ["doc"],
          },
          {
            prNumber: 25,
            prTitle: "Newer PR",
            prUrl: "https://github.com/example/repo/pull/25",
            mergedAt: "2026-02-01T00:00:00Z",
            contributionTypes: ["agents", "code"],
          },
        ],
      },
    ],
    1,
  );

  assert.match(md, /Missing contributors: 1/);
  assert.ok(md.indexOf("[#25]") < md.indexOf("[#10]"));
  assert.match(md, /@all-contributors please add @octocat for agents, code/);
  assert.match(md, /npx all-contributors add octocat agents,code,doc/);
});

test("normalizeCommitSha and evaluateRefShaConsistency validate 40-char hex SHAs", () => {
  const shaA = "a".repeat(40);
  const shaB = "b".repeat(40);

  assert.equal(normalizeCommitSha(`  ${shaA.toUpperCase()} `), shaA);
  assert.equal(normalizeCommitSha("short-sha"), undefined);
  assert.equal(normalizeCommitSha(null), undefined);

  assert.deepEqual(
    evaluateRefShaConsistency({ ref: "v1.0.0", sha: undefined, resolvedRefCommitSha: shaA }),
    {
      comparable: false,
      matches: true,
      normalizedSha: undefined,
      normalizedRefCommitSha: shaA,
    },
  );
  assert.equal(
    evaluateRefShaConsistency({ ref: "v1.0.0", sha: shaA, resolvedRefCommitSha: shaA }).matches,
    true,
  );
  assert.equal(
    evaluateRefShaConsistency({ ref: "v1.0.0", sha: shaA, resolvedRefCommitSha: shaB }).matches,
    false,
  );
});

test("parseRepoFromRemoteUrl, parseMissingContributorsOutput, and generatePRReport handle git remotes, check output, and PR file filtering", () => {
  assert.equal(parseRepoFromRemoteUrl("git@github.com:reevesc88/awesome-copilot.git"), "reevesc88/awesome-copilot");
  assert.equal(parseRepoFromRemoteUrl("ssh://git@github.com/octo/repo.git"), "octo/repo");
  assert.equal(parseRepoFromRemoteUrl("https://github.com/octo/repo"), "octo/repo");
  assert.equal(parseRepoFromRemoteUrl("https://gitlab.com/octo/repo.git"), null);
  assert.equal(parseRepoFromRemoteUrl(""), null);

  const sampleCheckOutput = [
    "⠙ Checking contributors",
    "Missing contributors in .all-contributorsrc:",
    "    alice, Dependabot[bot], bob ",
    "Unknown contributors found:",
    "    someone",
  ].join("\n");
  assert.deepEqual(
    parseMissingContributorsOutput(sampleCheckOutput, ["dependabot[bot]"]),
    ["alice", "bob"],
  );
  assert.deepEqual(parseMissingContributorsOutput("All contributors present!\n"), []);

  // PR touching only auto-generated files returns null unless includeAllFiles is true
  const generatedOnlyPr = {
    number: 7,
    title: "Regenerate docs",
    url: "https://github.com/octo/repo/pull/7",
    mergedAt: "2026-03-01T00:00:00Z",
    files: [{ path: "README.md", additions: 5, deletions: 2 }],
  };
  assert.equal(generatePRReport({ login: "alice" }, generatedOnlyPr), null);
  const includedAll = generatePRReport({ login: "alice" }, generatedOnlyPr, {
    includeAllFiles: true,
  });
  assert.deepEqual(includedAll.contributionTypes, ["doc"]);

  // Unrecognized non-generated file falls back to 'ideas'
  const miscPr = {
    number: 8,
    title: "Add binary fixture",
    url: "https://github.com/octo/repo/pull/8",
    mergedAt: "2026-03-02T00:00:00Z",
    files: [{ path: "assets/diagram.svg", additions: 1, deletions: 0 }],
  };
  const miscReport = generatePRReport({ login: "alice" }, miscPr);
  assert.deepEqual(miscReport.contributionTypes, ["ideas"]);
  assert.equal(miscReport.commentSnippet, "@all-contributors please add @alice for ideas");
});
